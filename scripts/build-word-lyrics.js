#!/usr/bin/env node

/**
 * Convert a word-timing export (array of {word, start, end, line_index}) into
 * the karaoke lyric structure the song page renders.
 *
 * Usage:
 *   node scripts/build-word-lyrics.js <timings.json> <track-slug>
 *
 * Writes/merges src/data/music-word-lyrics.json.
 */

const fs = require('fs');
const path = require('path');

const OUTPUT = path.resolve(__dirname, '../src/data/music-word-lyrics.json');

const [, , inputPath, slug] = process.argv;

if (!inputPath || !slug) {
  console.error('Usage: node scripts/build-word-lyrics.js <timings.json> <track-slug>');
  process.exit(1);
}

const raw = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
if (!Array.isArray(raw) || raw.length === 0) {
  console.error('Timing file must be a non-empty array of word objects.');
  process.exit(1);
}

// Group words by line_index, preserving the order they appear in.
const byLine = new Map();
for (const entry of raw) {
  const word = String(entry.word ?? '').trim();
  const start = Number(entry.start);
  const end = Number(entry.end);
  const lineIndex = Number.isFinite(Number(entry.line_index)) ? Number(entry.line_index) : 0;
  if (!word || !Number.isFinite(start)) continue;
  if (!byLine.has(lineIndex)) byLine.set(lineIndex, []);
  byLine.get(lineIndex).push({
    w: word,
    start: Number(start.toFixed(3)),
    end: Number.isFinite(end) ? Number(end.toFixed(3)) : Number(start.toFixed(3)),
  });
}

const lines = Array.from(byLine.entries())
  .sort((a, b) => a[0] - b[0])
  .map(([, words]) => {
    words.sort((a, b) => a.start - b.start);
    return {
      time: words[0].start,
      text: words.map((word) => word.w).join(' '),
      words,
    };
  });

let index = { tracks: {} };
if (fs.existsSync(OUTPUT)) {
  index = JSON.parse(fs.readFileSync(OUTPUT, 'utf8'));
  index.tracks = index.tracks || {};
}

index.tracks[slug] = lines;

const payload = {
  _readme:
    "Word-level karaoke lyrics keyed by track slug. Generated by scripts/build-word-lyrics.js from a word-timing export. Each line: {time, text, words:[{w,start,end}]}.",
  tracks: index.tracks,
};

fs.writeFileSync(OUTPUT, `${JSON.stringify(payload, null, 2)}\n`);
console.log(
  `Wrote ${lines.length} lines (${lines.reduce((n, l) => n + l.words.length, 0)} words) for ${slug}`
);
console.log(
  `First line @${lines[0].time}s: ${lines[0].text}\nLast line  @${lines[lines.length - 1].time}s: ${
    lines[lines.length - 1].text
  }`
);
